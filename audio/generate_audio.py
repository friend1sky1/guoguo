async def gen_one(file, text):
    com = edge_tts.Communicate(text, VOICE, rate=RATE)
    await com.save(file)
    print("OK", file)

def main():
    os.makedirs("audio", exist_ok=True)
    os.chdir("audio")
    for file, text in SONGS + LULLABIES:
        if text is None:
            shutil.copy("song1.mp3", file)
            print("OK", file, "(复制自 song1)")
        else:
            asyncio.run(gen_one(file, text))
    print("全部完成！28 个音频已生成")

if __name__ == "__main__":
    main()
